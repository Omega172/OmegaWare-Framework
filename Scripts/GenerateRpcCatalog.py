import argparse
import re
from collections import defaultdict
from pathlib import Path

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description="Lists every network function in a Dumper-7 SDK")
parser.add_argument("--sdk", default=str(root / "Source" / "Third-Party" / "Dumper-7" / "CppSDK" / "SDK"), help="folder with the *_functions.cpp files")
parser.add_argument("--out", default=str(root / "Docs" / "ServerRpcCatalog.md"), help="markdown file to write")
parser.add_argument("--game-module", default="Starbreeze", help="the game's own module name as it appears in 'Function <Module>.<Class>.<Name>'")
args = parser.parse_args()
sdk = Path(args.sdk)
out = Path(args.out)
game_module = args.game_module

engine_modules = {"Engine", "GameplayAbilities", "NetCore"}
pattern = re.compile(r"^// Function (\w+)\.(\w+)\.(\w+)\s*\n// \(([^)]*)\)", re.M)

catalog = defaultdict(lambda: defaultdict(list))
for path in sorted(sdk.glob("*_functions.cpp")):
    text = path.read_text(encoding="utf-8", errors="ignore")
    for module, cls, name, flags in pattern.findall(text):
        flag_set = {f.strip() for f in flags.split(",")}
        if "Net" not in flag_set:
            continue
        if module not in engine_modules and module != game_module:
            continue
        if module in engine_modules and cls not in {"CharacterMovementComponent", "PlayerController", "PlayerState", "GameModeBase", "GameMode", "Character", "Pawn", "Controller", "AbilitySystemComponent", "Actor"}:
            continue
        if "NetServer" in flag_set:
            kind = "server"
        elif "NetClient" in flag_set:
            kind = "client"
        elif "NetMulticast" in flag_set:
            kind = "multicast"
        else:
            kind = "other"
        catalog[(module, cls)][kind].append((name, "NetValidate" in flag_set, "NetReliable" in flag_set))

lines = [
    "# Network function catalog",
    "",
    "Generated by `Scripts/GenerateRpcCatalog.py` from the Dumper-7 SDK function flags. Do not edit by hand, rerun the script after dumping a new SDK.",
    "",
    "Meaning of the kinds:",
    "",
    "- **server**: a client calls it and the host runs it. If it has a `_Validate` check (marked V) the host kicks the caller when the check fails. This is the only way a client changes shared state.",
    "- **client**: the host calls it and a single client runs it. A client cannot trigger it for other players.",
    "- **multicast**: the host calls it and every machine runs it. Calling it from a client only runs it locally.",
    "",
    "R means reliable, V means the host validates the call.",
    "",
]
total = {"server": 0, "client": 0, "multicast": 0, "other": 0}
for (module, cls), kinds in sorted(catalog.items()):
    lines.append(f"## {module}.{cls}")
    lines.append("")
    for kind in ("server", "client", "multicast", "other"):
        entries = kinds.get(kind)
        if not entries:
            continue
        total[kind] += len(entries)
        rendered = ", ".join(f"`{n}`{' V' if v else ''}{' R' if r else ''}" for n, v, r in sorted(entries))
        lines.append(f"- **{kind}**: {rendered}")
    lines.append("")

lines.insert(3, f"Totals: {total['server']} server, {total['client']} client, {total['multicast']} multicast, {total['other']} other.")
lines.insert(4, "")
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {out} with {sum(total.values())} functions across {len(catalog)} classes")
